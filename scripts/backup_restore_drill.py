#!/usr/bin/env python3
"""Exercise encrypted backup recovery using only a disposable local PostgreSQL 16.

The PostgreSQL image must already be installed. No image is pulled, no host port
is exposed, and the container has no network. All fixture data is synthetic.
"""
import hashlib
import json
import os
from pathlib import Path
import secrets
import stat
import subprocess
import tempfile
import time
import uuid

from database_backup import BackupError, EMPTY_QUERY, backup_database, restore_database


FIXTURES = """
CREATE TABLE customers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text UNIQUE NOT NULL);
CREATE TABLE domains (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id integer NOT NULL REFERENCES customers(id), name text UNIQUE NOT NULL, provider_id bigint UNIQUE NOT NULL);
CREATE TABLE orders (id uuid PRIMARY KEY, owner_id integer NOT NULL REFERENCES customers(id),
 domain_id integer REFERENCES domains(id), amount_paise integer NOT NULL CHECK(amount_paise>0),
 status text NOT NULL, receipt text UNIQUE NOT NULL);
CREATE TABLE payments (id text PRIMARY KEY, order_id uuid REFERENCES orders(id),
 event_digest text NOT NULL, captured boolean NOT NULL);
CREATE TABLE audit (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id integer REFERENCES customers(id), order_id uuid REFERENCES orders(id), action text NOT NULL);
INSERT INTO customers(email) VALUES ('fixture-one@example.invalid'),('fixture-two@example.invalid');
INSERT INTO domains(owner_id,name,provider_id) VALUES (1,'fixture-one.invalid',9001),(2,'fixture-two.invalid',9002);
INSERT INTO orders VALUES
 ('10000000-0000-0000-0000-000000000001',1,1,129900,'active','fixture-order-one'),
 ('20000000-0000-0000-0000-000000000002',2,2,139900,'needs_review','fixture-order-two');
INSERT INTO payments VALUES
 ('fixture-payment-one','10000000-0000-0000-0000-000000000001','fixture-digest-one',true),
 ('fixture-payment-two','20000000-0000-0000-0000-000000000002','fixture-digest-two',true);
INSERT INTO audit(actor_id,order_id,action) VALUES
 (1,'10000000-0000-0000-0000-000000000001','registration_confirmed'),
 (2,'20000000-0000-0000-0000-000000000002','reconciliation_required');
"""

FINGERPRINT = """SELECT jsonb_build_object(
 'customers',(SELECT jsonb_agg(x ORDER BY id) FROM customers x),
 'domains',(SELECT jsonb_agg(x ORDER BY id) FROM domains x),
 'orders',(SELECT jsonb_agg(x ORDER BY id) FROM orders x),
 'payments',(SELECT jsonb_agg(x ORDER BY id) FROM payments x),
 'audit',(SELECT jsonb_agg(x ORDER BY id) FROM audit x))::text;"""


def docker(arguments, *, data=None, check=True):
    environment = os.environ.copy()
    for name in ("DOCKER_HOST", "DOCKER_CONTEXT", "DOCKER_TLS", "DOCKER_TLS_VERIFY", "DOCKER_CERT_PATH"):
        environment.pop(name, None)
    try:
        result = subprocess.run(["docker", "--host=unix:///var/run/docker.sock", *arguments],
                                input=data, stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=environment)
    except OSError:
        raise BackupError("The local Docker drill could not start") from None
    if check and result.returncode:
        raise BackupError(f"An isolated Docker drill operation failed (exit {result.returncode})")
    return result


def sql(container, database, query):
    return docker(["exec", "-i", container, "psql", "--no-psqlrc", "--set", "ON_ERROR_STOP=1",
                   "--username", "postgres", "--dbname", database, "--tuples-only", "--no-align"],
                  data=query.encode()).stdout.strip()


def expect_refusal(operation):
    try:
        operation()
    except BackupError:
        return
    raise BackupError("A required backup/restore refusal was not enforced")


def run_drill():
    run_id = uuid.uuid4().hex
    name = "domain-reseller-backup-drill-" + run_id
    label = "io.domainreseller.backup-drill"
    stage = "container startup"
    try:
        docker(["info", "--format", "{{.ServerVersion}}"])
        docker(["run", "--detach", "--pull", "never", "--name", name, "--label", f"{label}={run_id}",
                "--network", "none", "--memory", "256m", "--cpus", "1", "--pids-limit", "128",
                "--env", "POSTGRES_HOST_AUTH_METHOD=trust", "postgres:16-alpine"])
        for _ in range(60):
            ready = docker(["exec", name, "pg_isready", "--username", "postgres"], check=False)
            primary = docker(["exec", name, "cat", "/proc/1/comm"], check=False)
            # The image briefly starts a temporary server while initializing.
            if ready.returncode == 0 and primary.returncode == 0 and primary.stdout.strip() == b"postgres":
                break
            time.sleep(0.25)
        else:
            raise BackupError("The isolated PostgreSQL drill did not become ready")
        for database in ("fixture_source", "fixture_restored", "fixture_wrong_key", "fixture_corrupt", "fixture_occupied"):
            stage = "empty fixture databases"
            docker(["exec", name, "createdb", "--username", "postgres", "--template", "template0", database])
        stage = "synthetic source data"
        sql(name, "fixture_source", FIXTURES)
        source = sql(name, "fixture_source", FINGERPRINT)
        with tempfile.TemporaryDirectory(prefix="domain-reseller-backup-drill-") as directory:
            private = Path(directory)
            key, wrong_key, archive = private / "passphrase", private / "wrong-passphrase", private / "database.gpg"
            for path in (key, wrong_key):
                descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
                with os.fdopen(descriptor, "w") as output:
                    output.write(secrets.token_hex(32) + "\n")
            stage = "encrypted backup"
            backup_database(name, "postgres", "fixture_source", archive, key)
            if stat.S_IMODE(archive.stat().st_mode) != 0o600:
                raise BackupError("Encrypted archive permissions are not private")
            original_archive = hashlib.sha256(archive.read_bytes()).digest()
            expect_refusal(lambda: backup_database(name, "postgres", "fixture_source", archive, key))
            if hashlib.sha256(archive.read_bytes()).digest() != original_archive:
                raise BackupError("An existing encrypted archive was modified")
            stage = "verified restore"
            restore_database(name, "postgres", "fixture_restored", archive, key, "fixture_restored")
            restored = sql(name, "fixture_restored", FINGERPRINT)
            if source != restored:
                raise BackupError("Restored ownership/payment/audit fixture data does not match the source")
            # Identity sequences and unique/foreign-key/check constraints must survive.
            stage = "restored sequence and constraints"
            identifier = sql(name, "fixture_restored", "INSERT INTO customers(email) VALUES ('fixture-three@example.invalid') RETURNING id;")
            if not identifier.startswith(b"3\n"):
                raise BackupError("Restored identity sequence did not resume at the next value")
            for query in (
                "INSERT INTO domains(owner_id,name,provider_id) VALUES (99,'bad-owner.invalid',9998);",
                "INSERT INTO domains(owner_id,name,provider_id) VALUES (1,'fixture-one.invalid',9999);",
                "UPDATE orders SET amount_paise=0;",
            ):
                result = docker(["exec", "-i", name, "psql", "--no-psqlrc", "--set", "ON_ERROR_STOP=1",
                                 "--username", "postgres", "--dbname", "fixture_restored"], data=query.encode(), check=False)
                if result.returncode == 0:
                    raise BackupError("A restored data integrity constraint was not enforced")
            stage = "wrong-key refusal"
            expect_refusal(lambda: restore_database(name, "postgres", "fixture_wrong_key", archive, wrong_key, "fixture_wrong_key"))
            if sql(name, "fixture_wrong_key", EMPTY_QUERY) != b"empty":
                raise BackupError("Wrong-key input mutated the target")
            stage = "corruption refusal"
            corrupt = private / "corrupt.gpg"
            damaged = bytearray(archive.read_bytes())
            damaged[len(damaged) // 2] ^= 0x40
            corrupt.write_bytes(damaged)
            expect_refusal(lambda: restore_database(name, "postgres", "fixture_corrupt", corrupt, key, "fixture_corrupt"))
            if sql(name, "fixture_corrupt", EMPTY_QUERY) != b"empty":
                raise BackupError("Corrupt input mutated the target")
            stage = "occupied-target refusal"
            sql(name, "fixture_occupied", "CREATE TABLE sentinel(value text); INSERT INTO sentinel VALUES ('preserve fixture');")
            expect_refusal(lambda: restore_database(name, "postgres", "fixture_occupied", archive, key, "fixture_occupied"))
            if sql(name, "fixture_occupied", "SELECT value FROM sentinel;") != b"preserve fixture":
                raise BackupError("An occupied target was modified")
        return {"restored": "customer/domain/order/payment/audit fixtures", "ownership_and_sequences": "matched",
                "constraints": "enforced", "wrong_key": "refused without mutation", "corruption": "refused without mutation",
                "nonempty_target": "refused without mutation", "existing_archive": "preserved"}
    except BackupError as exc:
        raise BackupError(f"Drill stage '{stage}': {exc}") from None
    finally:
        # Only the unique container carrying this invocation's ownership label.
        inspection = docker(["inspect", "--format", "{{json .Config.Labels}}", name], check=False)
        if inspection.returncode == 0:
            try:
                labels = json.loads(inspection.stdout)
            except (ValueError, UnicodeDecodeError):
                raise BackupError("Cannot verify drill resource ownership; cleanup requires operator review") from None
            if isinstance(labels, dict) and labels.get(label) == run_id:
                docker(["rm", "--force", "--volumes", name])


if __name__ == "__main__":
    try:
        print(json.dumps(run_drill(), sort_keys=True))
    except BackupError as exc:
        raise SystemExit(str(exc)) from None
